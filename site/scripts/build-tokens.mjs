// Generates src/styles/tokens.css from ../brands/hometown.json so the brand JSON stays the
// single source of truth (CLAUDE.md: never hardcode brand values). Run: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const brandPath = resolve(here, '../../brands/hometown.json');
const outPath = resolve(here, '../src/styles/tokens.css');
const brand = JSON.parse(readFileSync(brandPath, 'utf8'));

const hex = (h) => h.replace('#', '');
const rgb = (h) => {
  const v = hex(h);
  return [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16)).join(' ');
};

const lines = [];
lines.push(`/* GENERATED by scripts/build-tokens.mjs from brands/${brand.id}.json. Do not edit by hand. */`);
lines.push(':root {');
lines.push(`  --brand-name: "${brand.name}";`);
for (const [k, v] of Object.entries(brand.colors)) {
  lines.push(`  --c-${k}: ${v};`);
  lines.push(`  --c-${k}-rgb: ${rgb(v)};`);
}
lines.push(`  --c-heart: #e12d32; /* logo heart, never recolored (HometownMark.tsx) */`);
lines.push(`  --c-heart-rgb: ${rgb('#e12d32')};`);
lines.push(`  --font-display: "${brand.fonts.display}", "Iowan Old Style", "Palatino Linotype", Georgia, serif;`);
lines.push(`  --font-body: "${brand.fonts.body}", "Helvetica Neue", Arial, system-ui, sans-serif;`);
lines.push(`  --font-mono: "${brand.fonts.mono}", "SFMono-Regular", Menlo, Consolas, monospace;`);
for (const [k, v] of Object.entries(brand.grade)) lines.push(`  --grade-${k}: ${v};`);
for (const [k, v] of Object.entries(brand.motion)) lines.push(`  --motion-${k}: ${typeof v === 'number' ? v : `"${v}"`};`);
lines.push('}');
writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`wrote ${outPath} (${lines.length} lines)`);
